#define INF 2147483647

#define PRINT_VEC(v)                                                           \
  for (const auto &pos : v) {                                                  \
    cout << pos << " ";                                                        \
  }                                                                            \
  cout << endl;

#define PRINT_DUO_VEC(v)                                                       \
  for (const auto &pos : v) {                                                  \
    cout << pos.first << " " << pos.second << endl;                            \
  }                                                                            \
  cout << endl;

#define INPUT_VEC(v)                                                           \
  for (auto &pos : v) {                                                        \
    cin >> pos;                                                                \
  }

#define INPUT_DUO_VEC(v)                                                       \
  for (auto &pos : v) {                                                        \
    cin >> pos.first >> pos.second;                                            \
  }

using namespace std;

int main(int argc, char *argv[]) {
  ios_base::sync_with_stdio(false);
  cin.tie(NULL);
  cout.tie(NULL);
  ll t;
  cin >> t;
  for (int i = 1; i <= t; i++) {
    ll n, m;
    cin >> n >> m;
    ll best = -INF;

    for (ll j = 0; j < n; j++) {
      ll a, b;
      cin >> a >> b;
      ll local = a - max(0LL, b - m);
      best = max(best, local);
    }

    cout << "Case #" << i << ": " << best << endl;
  }

  return 0;
}
